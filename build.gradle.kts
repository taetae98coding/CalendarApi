/**
 * 계층은 Gradle 모듈로 강제한다. 의존 방향은 아래로 고정이고, 거꾸로 부르면 컴파일이 실패한다.
 *
 * ```
 *              :app  (조립)
 *            /   |   \
 *      :publish  |   :data ---> :datasource
 *            \   |   /
 *             :domain
 *
 *      :core  (모든 모듈이 쓸 수 있는 바탕. 아무 모듈도 모른다)
 * ```
 *
 * - `:core` : 로그, JSON 파일 입출력, 산출물 폴더 정리. 달력도 원천도 모른다.
 * - `:domain` : 달력 자체의 개념. 다른 모듈을 모른다.
 * - `:datasource` : 원천에서 조회만 한다. 응답 원본을 그대로 돌려주고 도메인을 모른다.
 * - `:data` : 캐시를 성공/실패로 관리하고 갱신 우선순위와 동시성을 맡는다. 원본을 도메인으로 옮겨 저장소를 구현한다.
 * - `:publish` : 저장소에서 읽어 배포 문서를 쓴다. 원천을 모른다.
 * - `:app` : 설정을 읽고 위 모듈을 조립해 한 번의 실행을 진행한다.
 *
 * 모듈 공통 설정은 build-logic 의 `calendar.kotlin-jvm` 플러그인에 있다.
 */
